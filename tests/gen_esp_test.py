"""Build a host test for the ESP32 bridge's message parsers.

The parsers are sliced verbatim out of src/main.cpp at test time (from the
gate_status_t typedef through the end of gate_rx_message), so the test can never
drift from the shipping code. Everything ESP-IDF-specific is stubbed.
"""
import io
import os
import re

SRC = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..",
                   "esp32-wifi-bridge", "src", "main.cpp")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "esp_parsers.inc")

s = io.open(SRC, encoding="utf-8").read()

start = s.index("typedef struct {\n    int  state;")
end = s.index("static void json_escape(")
region = s[start:end]

# The region must contain the pieces we mean to test.
for need in ("parse_gate_status", "handle_evt_state", "handle_beam_edge",
             "handle_beam_activity", "gate_rx_message", "u32_after", "token_after"):
    assert need in region, "extracted region is missing " + need

io.open(OUT, "w", encoding="utf-8", newline="").write(
    "/* GENERATED by gen_esp_test.py - sliced verbatim from src/main.cpp. Do not edit. */\n"
    + region
)
print("wrote %s (%d bytes, %d lines)" % (OUT, len(region), region.count("\n")))
